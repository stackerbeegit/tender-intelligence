"""
Exercises the extractors against real files (generated by
scripts/generate_doc_fixtures.py) — a DOCX authored with python-docx, a
PDF converted from it via LibreOffice, an image-only PDF with no text
layer at all (for the needs_ocr path), a real XLSX, and a ZIP bundling
two of them. Not mocks: if pypdf/python-docx/openpyxl ever regress, these
fail for real.
"""
from pathlib import Path

import pytest

from app.core.exceptions import UnsupportedFileTypeError
from app.document_processing.extractors import extract_pages
from app.document_processing.validators import detect_content_type

FIXTURES_DIR = Path(__file__).parent.parent / "fixtures" / "documents"


def _read(name: str) -> bytes:
    return (FIXTURES_DIR / name).read_bytes()


def test_detects_docx_despite_generic_magic_database_result():
    data = _read("sample_native.docx")
    assert detect_content_type(data) == "application/vnd.openxmlformats-officedocument.wordprocessingml.document"


def test_detects_xlsx():
    data = _read("sample.xlsx")
    assert detect_content_type(data) == "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"


def test_detects_pdf():
    assert detect_content_type(_read("sample_native.pdf")) == "application/pdf"


def test_docx_extraction_recovers_real_text():
    pages, needs_ocr = extract_pages(_read("sample_native.docx"), "application/vnd.openxmlformats-officedocument.wordprocessingml.document")
    assert len(pages) == 1
    assert needs_ocr == [False]
    assert "Sample Tender Notice" in pages[0]
    assert "10,00,00,000" in pages[0]
    assert "Laptops" in pages[0]  # table cell text


def test_native_pdf_extraction_recovers_real_text_and_does_not_need_ocr():
    pages, needs_ocr = extract_pages(_read("sample_native.pdf"), "application/pdf")
    assert len(pages) == 1
    assert needs_ocr == [False]
    assert "Sample Tender Notice" in pages[0]


def test_scanned_pdf_has_no_extractable_text_and_needs_ocr():
    pages, needs_ocr = extract_pages(_read("sample_scanned.pdf"), "application/pdf")
    assert len(pages) == 1
    assert pages[0] == ""
    assert needs_ocr == [True]


def test_xlsx_extraction_recovers_sheet_and_cells():
    pages, needs_ocr = extract_pages(
        _read("sample.xlsx"), "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    )
    assert len(pages) == 1
    assert needs_ocr == [False]
    assert "BOQ" in pages[0]
    assert "Laptop - 16GB RAM" in pages[0]
    assert "55000" in pages[0]


def test_zip_bundle_extracts_every_member_with_filename_prefix():
    pages, needs_ocr = extract_pages(_read("sample_bundle.zip"), "application/zip")
    assert len(pages) == 2
    assert needs_ocr == [False, False]
    assert any("[File: NIT.pdf]" in p and "Sample Tender Notice" in p for p in pages)
    assert any("[File: BOQ.xlsx]" in p and "Laptop - 16GB RAM" in p for p in pages)


def test_unsupported_content_type_raises():
    with pytest.raises(UnsupportedFileTypeError):
        extract_pages(b"plain text, not a real document", "text/plain")
